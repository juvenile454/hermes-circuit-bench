VERDICTS = ("ok", "caution", "blocked")
OUTPUT_MODES = frozenset({"out", "pwm", "uart_tx", "spi_mosi", "spi_sck", "spi_cs", "i2c_sda", "i2c_scl"})
PULL_MODES = frozenset({"in_pullup", "in_pulldown"})
WHEN_KEYS = frozenset({"psram", "wifi", "variant"})
MAX_ALTERNATIVES = 3
MAX_SUGGEST_LIMIT = 10  # pins.suggest: suggestions per request (limit), default MAX_ALTERNATIVES
# Shared bus lines: several assignments on one GPIO with the same bus mode and the same net
# are one bus line, not a duplicate. Sources: NXP UM10204 Rev. 7 p. 4 (number of ICs on one I²C bus limited only by
# the bus capacitance), ESP-IDF v6.1 spi_master.rst, Terminology (devices share MOSI, MISO and SCLK; own CS line).
# spi_cs is per device and never shared.
BUS_MODES: dict[str, str] = {"i2c_sda": "nxp-um10204", "i2c_scl": "nxp-um10204", "spi_sck": "idf-v6.1-spi-master",
                             "spi_mosi": "idf-v6.1-spi-master", "spi_miso": "idf-v6.1-spi-master"}
_BUS_TEXT = {"nxp-um10204": "I²C devices share SDA and SCL; each needs its own address, and the bus capacitance "
                            "limits how many fit (UM10204)",
             "idf-v6.1-spi-master": "SPI devices share SCK, MOSI and MISO; each needs its own CS line (ESP-IDF SPI "
                                    "master docs)"}
SHARED_BUS_HINT = "If this is one bus line: give every device on a shared bus the same net."
_ROLE = re.compile(r"^[A-Z0-9_]{1,24}$")
_PIN = re.compile(r"^(?:gpio|io)?\s*(\d{1,3})$", re.IGNORECASE)
_RANK = {"info": 0, "caution": 1, "blocked": 2}
# engine findings (not rules from the data); titles feed summaries and `excluded[].why`
_TITLES = {"unknown_pin": "unknown pin", "not_broken_out": "not broken out", "no_adc": "no ADC channel",
           "no_touch": "no touch channel", "no_output": "input only", "no_pulls": "no internal pull",
           "duplicate_pin": "duplicate pin", "onboard": "used on the board", "shared_bus": "shared bus"}
_UNKNOWN_VARIANT = "Module variant unknown, confirm the module. If the condition holds ({cond}): {msg}"
_UNKNOWN_WIFI = "Depends on Wi-Fi (not given). With Wi-Fi on: {msg}"


# --- data -------------------------------------------------------------------------------------------------------------
def chips() -> list[str]:
    return sorted(p.stem for p in PINS_DIR.glob("*.json"))


def normalize_chip(chip: Any) -> str:
    """'ESP32-S3', 'esp32_s3', 'esp32s3' -> 'esp32s3'. Unknown -> BenchError unknown_chip."""
    known = chips()
    if not isinstance(chip, str) or re.sub(r"[\s_-]", "", chip.lower()) not in known:
        raise BenchError("unknown_chip", f"unknown chip {chip!r}", f"known chips: {', '.join(known)}")
    return re.sub(r"[\s_-]", "", chip.lower())


@lru_cache(maxsize=8)
def _data(chip: str) -> dict[str, Any]:
    path = PINS_DIR / f"{chip}.json"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise BenchError("rule_data_missing", f"pin data for {chip} unreadable: {e}",
                         "regenerate with scripts/gen_pins.py") from None
    if data.get("schema") != 1 or data.get("chip") != chip or not data.get("gpios"):
        raise BenchError("rule_data_missing", f"pin data for {chip} has an unexpected format")
    data["_by_num"] = {g["num"]: g for g in data["gpios"]}
    return data


def load(chip: str) -> dict[str, Any]:
    """Pin data as stored (deep copy)."""
    data = _data(normalize_chip(chip))
    return json.loads(json.dumps({k: v for k, v in data.items() if not k.startswith("_")}))


def clear_cache() -> None:
    _data.cache_clear()


def normalize_pin(pin: Any) -> int:
    """35, '35', 'GPIO35', 'IO35' -> 35. Anything else -> BenchError invalid_args."""
    if isinstance(pin, bool):
        raise BenchError("invalid_args", f"bad pin {pin!r}", "use a GPIO number such as 35 or 'GPIO35'")
    if isinstance(pin, int) and 0 <= pin < 1000:
        return pin
    if isinstance(pin, str):
        m = _PIN.match(pin.strip())
        if m:
            return int(m.group(1))
    raise BenchError("invalid_args", f"bad pin {pin!r}", "use a GPIO number such as 35 or 'GPIO35'")


# --- context ----------------------------------------------------------------------------------------------------------
class _Ctx:
    """Validated arguments plus the data they select. ``wifi=None`` means unknown (pins.info)."""

    def __init__(self, chip: Any, variant: Any, wifi: Any, devkit: Any, *, wifi_known: bool = True):
        self.chip = normalize_chip(chip)
        self.data = _data(self.chip)
        self.title = self.data["title"]
        self.gpios: dict[int, dict[str, Any]] = self.data["_by_num"]
        self.rules: list[dict[str, Any]] = self.data["rules"]
        self.variants = {v["id"]: v for v in self.data.get("variants", [])}
        if wifi_known and not isinstance(wifi, bool):
            raise BenchError("invalid_args", f"wifi must be true or false, not {wifi!r}")
        self.wifi: bool | None = wifi if wifi_known else None
        self.variant: dict[str, Any] | None = None
        if variant is not None:
            vid = variant.lower() if isinstance(variant, str) else variant
            if not self.variants:
                raise BenchError("invalid_args", f"no module variants known for {self.title}",
                                 "pass variant=None for this chip")
            if vid not in self.variants:
                raise BenchError("invalid_args", f"unknown module variant {variant!r} for {self.title}",
                                 f"known variants: {', '.join(self.variants)}")
            self.variant = self.variants[vid]
        self.devkit: str | None = None
        self.board: dict[str, Any] | None = None
        self.broken_out: set[int] = set()
        if devkit is not None:
            if not isinstance(devkit, str):
                raise BenchError("invalid_args", f"bad devkit {devkit!r}")
            board = boards.load(devkit)
            if board["chip"] != self.chip:
                raise BenchError("invalid_args", f"{board['title']} carries an {board['chip']}, not an {self.chip}")
            self.devkit, self.board = devkit, board
            self.broken_out = boards.broken_out(devkit)
        self._headers: dict[int, str | None] = {}

    @property
    def variant_unknown(self) -> bool:
        return bool(self.variants) and self.variant is None

    def header(self, num: int) -> str | None:
        if self.devkit is None:
            return None
        if num not in self._headers:
            self._headers[num] = boards.header_of(self.devkit, num)
        return self._headers[num]

    def label(self) -> str:
        if self.variant is not None:
            return f"{self.title} {self.variant['label']}"
        return f"{self.title} (module variant unknown)" if self.variants else self.title

    def condition(self, when: Mapping[str, Any]) -> bool | None:
        """True/False if the rule's `when` holds, None if it depends on something unknown."""
        state: bool | None = True
        for key, want in when.items():
            if key == "wifi":
                got = None if self.wifi is None else self.wifi == want
            elif key == "psram":
                got = None if self.variant is None else self.variant.get("psram") == want
            elif key == "variant":
                wanted = [want] if isinstance(want, str) else list(want)
                got = None if self.variant is None else self.variant["id"] in wanted
            else:
                raise BenchError("rule_data_missing", f"unsupported rule condition {key!r}")
            if got is False:
                return False
            if got is None:
                state = None
        return state


def _reason(rule_id: str, severity: str, message: str, source_id: str | None, title: str, *,
            unknown: bool = False, unverified: bool = False) -> dict[str, Any]:
    return {"rule_id": rule_id, "severity": severity, "message": message, "source_id": source_id,
            "_title": title, "_unknown": unknown, "_unverified": unverified}


def _public(reasons: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
    return [{k: v for k, v in r.items() if not k.startswith("_")} for r in reasons]


def _verdict(reasons: Iterable[Mapping[str, Any]]) -> str:
    rank = max((_RANK[r["severity"]] for r in reasons), default=0)
    return "blocked" if rank == 2 else "caution" if rank == 1 else "ok"


def _cond_text(when: Mapping[str, Any]) -> str:
    parts = []
    for key, want in when.items():
        if key == "psram":
            # "spi" (ESP32-WROVER): the ordering table names no bus width, so the text names the module type
            parts.append("a module with PSRAM, e.g. ESP32-WROVER" if want == "spi" else f"{want} PSRAM")
        elif key == "wifi":
            parts.append("Wi-Fi on" if want else "Wi-Fi off")
        else:
            parts.append(f"variant {want}")
    return ", ".join(parts)


def _rule_applies_to_mode(rule: Mapping[str, Any], mode: str) -> bool:
    return rule["modes"] == ["*"] or mode in rule["modes"]


def _evaluate(ctx: _Ctx, num: int, mode: str) -> list[dict[str, Any]]:
    """Findings for one pin in one mode, without the duplicate check. Order is fixed."""
    g = ctx.gpios.get(num)
    caps = ctx.data["capabilities"]
    if g is None:
        return [_reason("unknown_pin", "blocked", f"{ctx.title} has no GPIO{num}.", caps["gpio"]["source_id"],
                        _TITLES["unknown_pin"])]
    out: list[dict[str, Any]] = []
    if ctx.board is not None and num not in ctx.broken_out:
        out.append(_reason("not_broken_out", "blocked", f"GPIO{num} is not broken out on the {ctx.board['title']} "
                           f"{ctx.board.get('revision') or ''}".rstrip() + " headers.",
                           ctx.board["source_id"], _TITLES["not_broken_out"]))
    if mode == "adc" and g["adc"] is None:
        out.append(_reason("no_adc", "blocked", f"GPIO{num} has no ADC channel.", caps["adc"]["source_id"],
                           _TITLES["no_adc"]))
    if mode == "touch" and g.get("touch") is None:
        msg = (f"GPIO{num} has no touch channel." if caps["touch"]["supported"]
               else f"{ctx.title} has no touch sensor.")
        out.append(_reason("no_touch", "blocked", msg, caps["touch"]["source_id"], _TITLES["no_touch"]))
    for rule in ctx.rules:
        if num not in rule["pins"] or not _rule_applies_to_mode(rule, mode):
            continue
        state = ctx.condition(rule.get("when", {}))
        if state is False:
            continue
        severity, message = rule["severity"], rule["message"]
        if state is None and severity != "info":
            severity = "caution"
            template = _UNKNOWN_WIFI if "wifi" in rule["when"] and ctx.wifi is None else _UNKNOWN_VARIANT
            message = template.format(cond=_cond_text(rule["when"]), msg=message)
        out.append(_reason(rule["id"], severity, message, rule["source_id"], rule["title"],
                           unknown=state is None, unverified=bool(rule.get("unverified"))))
    hard = any(r["severity"] == "blocked" for r in out)
    if mode in OUTPUT_MODES and g["input_only"] and not hard:
        out.append(_reason("no_output", "blocked", f"GPIO{num} is input only.", caps["output"]["source_id"],
                           _TITLES["no_output"]))
    if mode in PULL_MODES and not g["internal_pulls"] and not hard:
        out.append(_reason("no_pulls", "blocked", f"GPIO{num} has no internal pull resistors.",
                           caps["gpio"]["source_id"], _TITLES["no_pulls"]))
    if ctx.board is not None:
        for part in ctx.board.get("onboard", []):
            if part.get("gpio") == num:
                out.append(_reason("onboard", part.get("severity", "caution"),
                                   f"Used on the {ctx.board['title']}: {part['what']}.",
                                   part.get("source_id", ctx.board["source_id"]), f"on board: {part['what']}"))
    return out


def _main_reason(reasons: list[dict[str, Any]]) -> dict[str, Any] | None:
    hits = [r for r in reasons if r["severity"] != "info"] or reasons
    return max(hits, key=lambda r: _RANK[r["severity"]], default=None)


def _strapping_pins(ctx: _Ctx) -> set[int]:
    return {p for r in ctx.rules if r["id"].endswith(".strapping") for p in r["pins"]}


def _candidates(ctx: _Ctx, mode: str, *, exclude: Mapping[int, str], requested: int | None,
                limit: int = MAX_ALTERNATIVES) -> dict[str, Any]:
    """Deterministic suggestion list: pins without findings, mode preference, ascending GPIO number."""
    strapping = _strapping_pins(ctx)
    suggestions: list[dict[str, Any]] = []
    excluded: list[dict[str, Any]] = []
    for num in sorted(ctx.gpios):
        if len(suggestions) >= limit:
            break
        g = ctx.gpios[num]
        why = None
        if num == requested:
            why = "requested pin"
        elif num in exclude:
            why = exclude[num]
        elif mode == "adc" and (g["adc"] is None or g["adc"]["unit"] != 1):
            why = "no ADC channel" if g["adc"] is None else f"ADC{g['adc']['unit']} (adc prefers ADC1)"
        elif mode in ("out", "pwm") and num in strapping:
            why = "strapping pin (caution)"
        else:
            reasons = _evaluate(ctx, num, mode)
            if reasons:
                main = _main_reason(reasons) or reasons[0]
                why = f"{main['_title']} ({main['severity']})"
        if why is None:
            suggestions.append({"gpio": num, "header": ctx.header(num)})
        else:
            excluded.append({"gpio": num, "why": why})
    return {"suggestions": suggestions, "excluded": excluded}


def _validate_mode(mode: Any) -> str:
    if mode not in MODES:
        raise BenchError("invalid_args", f"unknown mode {mode!r}", f"modes: {', '.join(MODES)}")
    return mode


def _validate_net(net: Any) -> str | None:
    """Net name or None (missing or empty); only compared, never stored here."""
    if net is None:
        return None
    if not isinstance(net, str):
        raise BenchError("invalid_args", f"bad net {net!r}", "net: a name such as I2C_SDA")
    return net.strip() or None


def _shared_bus_pins(items: list[dict[str, Any]], counts: Mapping[int, int]) -> set[int]:
    """GPIOs used more than once where every assignment has the same bus mode and the same non-empty net."""
    out = set()
    for num, n in counts.items():
        if n < 2:
            continue
        group = [it for it in items if it["pin"] == num]
        modes, nets = {it["mode"] for it in group}, {it["net"] for it in group}
        if len(modes) == 1 and next(iter(modes)) in BUS_MODES and len(nets) == 1 and None not in nets:
            out.add(num)
    return out


def _validate_role(role: Any) -> str | None:
    if role is None:
        return None
    if not isinstance(role, str) or not _ROLE.match(role):
        raise BenchError("invalid_args", f"bad role {role!r}", "role: [A-Z0-9_]{1,24}, e.g. LASER or BUTTON")
    return role


def _sources_for(ids: Iterable[str | None]) -> list[dict[str, Any]]:
    return sources.resolve(i for i in ids if i)


def _devkit_module(ctx: _Ctx) -> dict[str, Any] | None:
    """The DevKit's module if its variant is one of the chip's variants (and it names its source), else None."""
    module = (ctx.board or {}).get("module")
    if not isinstance(module, Mapping) or module.get("variant") not in ctx.variants or not module.get("source_id"):
        return None
    return dict(module)


def _module_source(ctx: _Ctx) -> list[str]:
    module = _devkit_module(ctx) if ctx.variant_unknown else None
    return [module["source_id"]] if module else []


def _common_notes(ctx: _Ctx) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    warnings: list[dict[str, Any]] = []
    assumptions: list[dict[str, Any]] = []
    if ctx.variant_unknown:
        text = (f"{ctx.title} module variant unknown: pins that depend on the PSRAM type are not checked. Confirm the "
                f"module (known: {', '.join(v['label'] for v in ctx.variants.values())}).")
        ids = [ctx.variants[next(iter(ctx.variants))]["source_id"]]
        module = _devkit_module(ctx)
        if module is not None:  # a hint only, the verdicts stay as without a variant
            text += (f" The DevKit is sold with module {module['name']} (variant {module['variant']}, ordering "
                     f"information): pass variant={module['variant']} if your board carries it.")
            ids.append(module["source_id"])
        warnings.append(warning("variant_unknown", "caution", text, ids))
        assumptions.append(assumption("variant", "unknown", "module not confirmed; PSRAM-dependent rules not checked"))
    if ctx.devkit is None:
        assumptions.append(assumption("devkit", "none", "bare module: header positions and on-board parts not checked"))
    return warnings, assumptions


# --- pins.check -------------------------------------------------------------------------------------------------------
def check(chip: Any, assignments: Any, *, variant: Any = None, wifi: Any = False, devkit: Any = None,
          parts: Any = None, options: Any = None) -> dict[str, Any]:
    """Verdict per assignment ({role?, mode, pin, net?}); checks per rule group. One GPIO with the same bus mode
    (I²C SDA/SCL, SPI SCK/MOSI/MISO) and the same non-empty net in every assignment is a shared bus (info).
    ``parts``/``options`` (the project's): module instances among the parts add the module checks;
    without modules the answer is unchanged."""
    try:
        env = _check(chip, assignments, variant=variant, wifi=wifi, devkit=devkit)
        if parts and env.get("ok"):
            env = _with_modules(env, assignments, parts, options, devkit)
        return env
    except BenchError as e:
        return from_error("pins.check", e)


DISCRETE_REFS_SHOWN = 6


def _with_discrete_note(env: dict[str, Any], parts: Any) -> dict[str, Any]:
    """Add the assumption ``discrete_parts`` when a wired part is not a catalog module instance (those parts get no
    electrical check of their own; module rules only count the pull-ups, series resistors and diodes they need).
    Parts without ``conn`` do not count; no such part -> ``env`` unchanged."""
    refs = [str(p.get("ref") or "?") for p in parts
            if isinstance(p, Mapping) and not p.get("module") and p.get("conn")]
    if not refs:
        return env
    shown = ", ".join(refs[:DISCRETE_REFS_SHOWN]) + (", …" if len(refs) > DISCRETE_REFS_SHOWN else "")
    note = assumption("discrete_parts", str(len(refs)), f"{shown}: discrete parts get no electrical check of their own; "
                      "only pin rules and catalog-module rules ran. Size them with bench_calc.")
    return {**env, "assumptions": [*env.get("assumptions", []), note]}


def _with_modules(env: dict[str, Any], assignments: Any, parts: Any, options: Any, devkit: Any) -> dict[str, Any]:
    """Merge modcheck.run into the pins.check envelope. No module instance -> ``env`` unchanged.
    ``result.modules`` = the engine result; checks/warnings appended; cited sources appended (an unknown source id
    becomes a ``rule_data_missing`` warning, never an error); the summary gains the module tally."""
    from . import modcheck

    if not isinstance(parts, list | tuple):
        return env
    env = _with_discrete_note(env, parts)
    res = env["result"]
    try:
        report = modcheck.run(chip=res["chip"], assignments=list(assignments), parts=list(parts),
                              options=options if isinstance(options, Mapping) else None, devkit=res.get("devkit"))
    except Exception as e:  # noqa: BLE001 - the module checks must never break the pin checks
        env["warnings"].append(warning("rule_data_missing", "info", f"module checks unavailable: {type(e).__name__}"))
        return env
    if report is None:
        return env
    out = env
    small = report
    for level in range(len(modcheck.SHRINK_LEVELS)):
        small = modcheck.shrink(report, level)
        out = _merge_modules(env, small)
        if _fits(out):
            return out
    # still too large (very many modules): drop module warnings from the end (dangers come first) and say so in
    # counts.hidden; the answer never exceeds MAX_RESULT_BYTES
    while small.warnings and not _fits(out):
        w = small.warnings[-1]
        counts = {**small.result["counts"], "shown": len(small.warnings) - 1,
                  "hidden": [f"{w['code']} {','.join(w.get('refs') or [])}".strip(),
                             *small.result["counts"].get("hidden", [])][: modcheck.MAX_HIDDEN_LISTED]}
        small = modcheck.ModReport(result={**small.result, "counts": counts}, checks=small.checks,
                                   warnings=small.warnings[:-1], source_ids=small.source_ids, findings=small.findings)
        out = _merge_modules(env, small)
    return out


_OK_PIN_KEYS = ("role", "mode", "pin", "name", "verdict", "net")


def _modcheck() -> Any:
    from . import modcheck
    return modcheck


def _fits(env: Mapping[str, Any]) -> bool:
    return len(json.dumps(env).encode()) <= MAX_RESULT_BYTES  # ASCII escapes: the larger of both measures


def _merge_modules(env: dict[str, Any], report: Any) -> dict[str, Any]:
    out = {**env, "result": {**env["result"], "modules": report.result}, "checks": [*env["checks"], *report.checks],
           "warnings": [*env["warnings"], *report.warnings], "sources": list(env["sources"])}
    if (report.result.get("compact") or 0) >= len(_modcheck().SHRINK_LEVELS) - 1:  # last resort: no source notes
        out["sources"] = [{k: v for k, v in x.items() if k != "note"} for x in out["sources"]]
        out["result"]["pins"] = [{k: v for k, v in x.items() if k in _OK_PIN_KEYS} if x.get("verdict") == "ok"
                                 else x for x in out["result"].get("pins", [])]  # ok pins: no function lists
    have = {s.get("id") for s in out["sources"]}
    missing = []
    for sid in report.source_ids:
        if sid in have:
            continue
        try:
            src = sources.resolve([sid])
            if report.result.get("compact"):  # compact answers cite id, title, url and date (the note stays in data)
                src = [{k: v for k, v in x.items() if k != "note"} for x in src]
            out["sources"] += src
            have.add(sid)
        except BenchError:
            missing.append(sid)
    if missing:
        out["warnings"].append(warning("rule_data_missing", "info", "module findings cite unknown sources: "
                                       + ", ".join(missing[:5]) + ("…" if len(missing) > 5 else "")))
    c = report.result["counts"]
    out["summary"] = env["summary"] + (f" Modules: {c['findings']} finding{'' if c['findings'] == 1 else 's'} "
                                          f"({c['danger']} danger, {c['caution']} caution).")
    return out


def _check(chip: Any, assignments: Any, *, variant: Any, wifi: Any, devkit: Any) -> dict[str, Any]:
    ctx = _Ctx(chip, variant, wifi, devkit)
    if not isinstance(assignments, list | tuple) or not assignments:
        raise BenchError("invalid_args", "assignments must be a non-empty list of {role, mode, pin}")
    items = []
    for i, a in enumerate(assignments):
        if not isinstance(a, Mapping):
            raise BenchError("invalid_args", f"assignment {i} is not an object")
        items.append({"role": _validate_role(a.get("role")), "mode": _validate_mode(a.get("mode")),
                      "pin": normalize_pin(a.get("pin")), "net": _validate_net(a.get("net"))})
    if len(items) > len(ctx.gpios):
        raise BenchError("invalid_args", f"{len(items)} assignments, but {ctx.title} has {len(ctx.gpios)} GPIOs")

    counts: dict[int, int] = {}
    for it in items:
        counts[it["pin"]] = counts.get(it["pin"], 0) + 1
    shared = _shared_bus_pins(items, counts)
    entries = []
    found: list[tuple[int, dict[str, Any]]] = []  # (pin, reason) for the checks
    for idx, it in enumerate(items):
        num, mode = it["pin"], it["mode"]
        reasons = _evaluate(ctx, num, mode)
        if counts[num] > 1:
            others = [o["role"] or o["mode"] for j, o in enumerate(items) if o["pin"] == num and j != idx]
            if num in shared:
                src = BUS_MODES[mode]
                reasons.append(_reason("shared_bus", "info", f"GPIO{num} is a shared bus line ({mode}, net "
                                       f"{it['net']}) with {', '.join(others)}: {_BUS_TEXT[src]}.", src,
                                       _TITLES["shared_bus"]))
            else:
                same_bus = {o["mode"] for o in items if o["pin"] == num} == {mode} and mode in BUS_MODES
                reasons.append(_reason("duplicate_pin", "blocked", f"GPIO{num} is also assigned to {', '.join(others)}."
                                       + (f" {SHARED_BUS_HINT}" if same_bus else ""), None, _TITLES["duplicate_pin"]))
        found += [(num, r) for r in reasons]
        verdict = _verdict(reasons)
        alternatives: list[int] = []
        if verdict != "ok":
            exclude = {o["pin"]: f"taken by {o['role'] or o['mode']}" for j, o in enumerate(items) if j != idx}
            alternatives = [s["gpio"] for s in _candidates(ctx, mode, exclude=exclude, requested=num)["suggestions"]]
        g = ctx.gpios.get(num)
        entries.append({
            "role": it["role"], "mode": mode, "pin": num, "name": f"GPIO{num}", "verdict": verdict,
            "rule_ids": list(dict.fromkeys(r["rule_id"] for r in reasons)),
            "reasons": _public(reasons), "functions": list(g["functions"]) if g else [],
            "header": ctx.header(num), "alternatives": alternatives,
            "_main": _main_reason(reasons),
        })

    checks = _checks(ctx, items, found, counts, shared)
    tally = {v: sum(e["verdict"] == v for e in entries) for v in VERDICTS}
    worst = "blocked" if tally["blocked"] else "caution" if tally["caution"] else None
    detail = ""
    if worst:
        named = list(dict.fromkeys(f"GPIO{e['pin']}: {e['_main']['_title']}" for e in entries if e["verdict"] == worst))
        detail = " (" + "; ".join(named[:3]) + ("; …" if len(named) > 3 else "") + ")"
    summary = (f"{ctx.label()}, Wi-Fi {'on' if ctx.wifi else 'off'}: {tally['ok']} ok, {tally['caution']} caution, "
               f"{tally['blocked']} blocked{detail}.")
    for e in entries:
        del e["_main"]
    warnings, assumptions = _common_notes(ctx)
    src_ids = [ctx.data["capabilities"]["gpio"]["source_id"]] + [r["source_id"] for _, r in found]
    if ctx.board is not None:
        src_ids.append(ctx.board["source_id"])
    if ctx.variant_unknown:
        src_ids += [w for warn in warnings for w in warn["source_ids"]]
    result = {"chip": ctx.chip, "title": ctx.title, "variant": ctx.variant["id"] if ctx.variant else None,
              "wifi": ctx.wifi, "devkit": ctx.devkit, "counts": tally, "pins": entries}
    return envelope("pins.check", summary, result, checks=checks, warnings=warnings, assumptions=assumptions,
                    sources=_sources_for(src_ids))


def _pins_text(pins: Iterable[int]) -> str:
    return ", ".join(f"GPIO{p}" for p in sorted(set(pins)))


def _checks(ctx: _Ctx, items: list[dict[str, Any]], found: list[tuple[int, dict[str, Any]]],
            counts: Mapping[int, int], shared: set[int]) -> list[dict[str, Any]]:
    def hits(*rule_ids: str) -> list[tuple[int, dict[str, Any]]]:
        return [(n, r) for n, r in found if r["rule_id"] in rule_ids]

    out = []
    missing = [n for n, _ in hits("unknown_pin")]
    out.append(mk_check("pins.exists", "failed" if missing else "passed",
                        f"not on {ctx.title}: {_pins_text(missing)}" if missing
                        else f"all {len(items)} pins exist on {ctx.title}"))
    modes = hits("no_adc", "no_touch", "no_output", "no_pulls")
    out.append(mk_check("pins.modes", "failed" if modes else "passed",
                        "; ".join(f"GPIO{n}: {r['_title']}" for n, r in modes) if modes
                        else "every pin supports its mode"))
    dups = sorted(n for n, c in counts.items() if c > 1 and n not in shared)
    bus = f"shared bus (same mode and net): {_pins_text(shared)}" if shared else ""
    text = f"used twice: {_pins_text(dups)}" if dups else "no pin used twice"
    out.append(mk_check("pins.duplicates", "failed" if dups else "passed", f"{text}; {bus}" if bus else text))
    if ctx.board is None:
        out.append(mk_check("pins.broken_out", "skipped", "no devkit given"))
        out.append(mk_check("pins.board", "skipped", "no devkit given"))
    else:
        nb = [n for n, _ in hits("not_broken_out")]
        name = f"{ctx.board['title']} {ctx.board.get('revision') or ''}".rstrip()
        out.append(mk_check("pins.broken_out", "failed" if nb else "passed",
                            f"not on the {name} headers: {_pins_text(nb)}" if nb else f"all on the {name} headers"))
        ob = hits("onboard")
        bad = [(n, r) for n, r in ob if r["severity"] != "info"]
        out.append(mk_check("pins.board", "failed" if bad else "passed",
                            "; ".join(f"GPIO{n}: {r['_title']}" for n, r in ob) if ob else "no on-board part affected"))
    for rule in ctx.rules:
        rh = hits(rule["id"])
        cid = "pins." + rule["id"].split(".", 1)[-1]
        failed = [n for n, r in rh if r["severity"] != "info" and not r["_unknown"]]
        unknown = [n for n, r in rh if r["_unknown"] or r["_unverified"]]
        if failed:
            out.append(mk_check(cid, "failed", f"{_pins_text(failed)}: {rule['title']} ({rule['severity']})"))
        elif unknown:
            why = "unverified" if rule.get("unverified") else "depends on " + _cond_text(rule.get("when", {}))
            out.append(mk_check(cid, "not_checked", f"{_pins_text(unknown)}: {rule['title']}, {why}"))
        elif rh:
            out.append(mk_check(cid, "passed", f"hint only: {_pins_text(n for n, _ in rh)}"))
        else:
            out.append(mk_check(cid, "passed", "no assigned pin affected"))
    return out


# --- pins.suggest -----------------------------------------------------------------------------------------------------
def suggest(chip: Any, requests: Any, *, variant: Any = None, wifi: Any = False, devkit: Any = None,
            taken: Any = (), limit: Any = None) -> dict[str, Any]:
    """Up to ``limit`` (default 3, at most MAX_SUGGEST_LIMIT) pins without findings per request ({role?, mode,
    pin?}), ascending GPIO number; per request ``free`` = every pin without findings, ``more`` = those not shown."""
    try:
        return _suggest(chip, requests, variant=variant, wifi=wifi, devkit=devkit, taken=taken, limit=limit)
    except BenchError as e:
        return from_error("pins.suggest", e)


def _suggest_limit(limit: Any) -> int:
    if limit is None:
        return MAX_ALTERNATIVES
    if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= MAX_SUGGEST_LIMIT:
        raise BenchError("invalid_args", f"limit must be an integer from 1 to {MAX_SUGGEST_LIMIT}",
                         f"default {MAX_ALTERNATIVES}; result.requests[].more counts the free pins not shown")
    return limit


def _suggest(chip: Any, requests: Any, *, variant: Any, wifi: Any, devkit: Any, taken: Any,
             limit: Any = None) -> dict[str, Any]:
    ctx = _Ctx(chip, variant, wifi, devkit)
    limit = _suggest_limit(limit)
    if not isinstance(requests, list | tuple) or not requests:
        raise BenchError("invalid_args", "requests must be a non-empty list of {role, mode, pin?}")
    if len(requests) > 16:
        raise BenchError("invalid_args", "at most 16 requests per call")
    if isinstance(taken, str | bytes | Mapping) or not isinstance(taken, Iterable):
        raise BenchError("invalid_args", "taken must be a list of GPIO numbers")
    taken_set = {normalize_pin(t) for t in taken}
    out = []
    for i, rq in enumerate(requests):
        if not isinstance(rq, Mapping):
            raise BenchError("invalid_args", f"request {i} is not an object")
        role, mode = _validate_role(rq.get("role")), _validate_mode(rq.get("mode"))
        requested = None if rq.get("pin") is None else normalize_pin(rq.get("pin"))
        found = _candidates(ctx, mode, exclude=dict.fromkeys(taken_set, "taken"), requested=requested, limit=limit)
        free = len(_all_candidates(ctx, mode, taken_set, requested))
        out.append({"role": role, "mode": mode, "requested": requested, **found, "free": free,
                    "more": free - len(found["suggestions"])})

    def label(r: Mapping[str, Any]) -> str:
        return f"{r['role']} ({r['mode']})" if r["role"] else f"mode {r['mode']}"

    def gpios(r: Mapping[str, Any]) -> str:
        return ", ".join(f"GPIO{s['gpio']}" for s in r["suggestions"]) or "none"

    if len(out) == 1:
        r = out[0]
        instead = f" instead of GPIO{r['requested']}" if r["requested"] is not None else ""
        summary = (f"Free pins for {label(r)}{instead}: {gpios(r)}." if r["suggestions"]
                   else f"No pin without findings for {label(r)}{instead}.")
    else:
        summary = f"Free pins for {len(out)} requests: " + "; ".join(f"{label(r)}: {gpios(r)}" for r in out) + "."
    allocation = None
    if len(out) > 1:  # several requests: one distinct pin each where possible
        allocation = _allocate(ctx, out, taken_set)
        for a, r in zip(allocation, out, strict=True):
            a["beyond_suggestions"] = a["gpio"] is not None and a["gpio"] not in [s["gpio"] for s in r["suggestions"]]
        picked = [f"{label(a)} GPIO{a['gpio']}" for a in allocation if a["gpio"] is not None]
        summary += f" Picks without overlap: {', '.join(picked) or 'none'}."
        beyond = [f"GPIO{a['gpio']}" for a in allocation if a["beyond_suggestions"]]
        if beyond:
            summary += (f" {', '.join(beyond)} {'is' if len(beyond) == 1 else 'are'} beyond the shown suggestions "
                        "and passed the same checks (no findings).")
    warnings, assumptions = _common_notes(ctx)
    for r in out:
        if not r["suggestions"]:
            warnings.append(warning("no_suggestion", "caution", f"no pin without findings for {label(r)}"))
    checks = [mk_check("suggest.ok_only", "passed", "only pins without findings"),
              mk_check("suggest.order", "passed", f"ascending GPIO number, no other tie-break; up to {limit} per "
                       "request (limit), more = free pins not shown")]
    if ctx.board is None:
        checks.append(mk_check("suggest.broken_out", "skipped", "no devkit given"))
    else:
        checks.append(mk_check("suggest.broken_out", "passed", f"only pins on the {ctx.board['title']} headers"))
    if allocation is not None:
        short = [label(a) for a in allocation if a["gpio"] is None]
        checks.append(mk_check("suggest.distinct", "failed" if short else "passed",
                               f"no distinct pin left for {', '.join(short)}" if short
                               else "allocation: one distinct pin per request (other requests and taken excluded); "
                               "beyond_suggestions picks passed the same checks (no findings)"))
    if ctx.variant_unknown:
        checks.append(mk_check("suggest.variant", "not_checked",
                               "module variant unknown: PSRAM-dependent pins left out"))
    src_ids = [ctx.data["capabilities"]["gpio"]["source_id"]] + [r["source_id"] for r in ctx.rules]
    if ctx.board is not None:
        src_ids.append(ctx.board["source_id"])
    src_ids += _module_source(ctx)
    result = {"chip": ctx.chip, "title": ctx.title, "variant": ctx.variant["id"] if ctx.variant else None,
              "wifi": ctx.wifi, "devkit": ctx.devkit, "taken": sorted(taken_set), "requests": out}
    if allocation is not None:
        result["allocation"] = allocation
    return envelope("pins.suggest", summary, result, checks=checks, warnings=warnings, assumptions=assumptions,
                    sources=_sources_for(src_ids))


def _all_candidates(ctx: _Ctx, mode: str, taken: set[int], requested: int | None) -> list[int]:
    """Every pin _candidates would suggest for ``mode`` (no length limit), ascending."""
    found = _candidates(ctx, mode, exclude=dict.fromkeys(taken, "taken"), requested=requested, limit=len(ctx.gpios))
    return [s["gpio"] for s in found["suggestions"]]


def _allocate(ctx: _Ctx, reqs: list[Mapping[str, Any]], taken: set[int]) -> list[dict[str, Any]]:
    """One distinct pin per request (bipartite matching, Kuhn's augmenting paths): requests in the given order, pins
    ascending, so the answer is deterministic and as many requests as possible get a pin of their own."""
    cands = [_all_candidates(ctx, r["mode"], taken, r["requested"]) for r in reqs]
    owner: dict[int, int] = {}

    def place(i: int, seen: set[int]) -> bool:
        for g in cands[i]:
            if g in seen:
                continue
            seen.add(g)
            if g not in owner or place(owner[g], seen):
                owner[g] = i
                return True
        return False

    for i in range(len(reqs)):
        place(i, set())
    pick = {i: g for g, i in owner.items()}
    return [{"role": r["role"], "mode": r["mode"], "gpio": pick.get(i)} for i, r in enumerate(reqs)]


# --- pins.info --------------------------------------------------------------------------------------------------------
def info(chip: Any, pin: Any, *, variant: Any = None, devkit: Any = None) -> dict[str, Any]:
    """Functions, rules (with `applies` for this variant) and header position of one GPIO."""
    try:
        return _info(chip, pin, variant=variant, devkit=devkit)
    except BenchError as e:
        return from_error("pins.info", e)


def _info(chip: Any, pin: Any, *, variant: Any, devkit: Any) -> dict[str, Any]:
    ctx = _Ctx(chip, variant, None, devkit, wifi_known=False)
    num = normalize_pin(pin)
    g = ctx.gpios.get(num)
    if g is None:
        raise BenchError("unknown_pin", f"{ctx.title} has no GPIO{num}",
                         f"GPIOs: {', '.join(str(n) for n in sorted(ctx.gpios))}")
    rules = []
    for rule in ctx.rules:
        if num not in rule["pins"]:
            continue
        entry = {"rule_id": rule["id"], "title": rule["title"], "severity": rule["severity"],
                 "message": rule["message"], "source_id": rule["source_id"], "when": dict(rule.get("when", {})),
                 "modes": list(rule["modes"]), "applies": ctx.condition(rule.get("when", {}))}
        if rule.get("unverified"):
            entry["unverified"] = True
        rules.append(entry)
    modes = {m: _verdict(_evaluate(ctx, num, m)) for m in MODES}
    onboard = [dict(p) for p in (ctx.board or {}).get("onboard", []) if p.get("gpio") == num]
    result = {
        "chip": ctx.chip, "title": ctx.title, "variant": ctx.variant["id"] if ctx.variant else None,
        "devkit": ctx.devkit, "gpio": num, "name": f"GPIO{num}", "header": ctx.header(num),
        "broken_out": None if ctx.board is None else num in ctx.broken_out,
        "functions": list(g["functions"]), "rtc": g["rtc"], "adc": g["adc"], "touch": g.get("touch"),
        "input_only": g["input_only"], "internal_pulls": g["internal_pulls"],
        "rules": rules, "onboard": onboard, "modes": modes,
    }
    shown = [f for f in g["functions"] if f != f"GPIO{num}"][:4]
    hard = [r for r in rules if r["severity"] != "info" and r["applies"] is not False]
    parts = []
    for r in hard:
        cond = ""
        if r["when"]:
            cond = f" ({ctx.variant['label']})" if r["applies"] and ctx.variant else f" (if {_cond_text(r['when'])})"
        parts.append(f"{r['severity']}: {r['title']}{cond}")
    if ctx.board is not None and num not in ctx.broken_out:
        parts.insert(0, "not broken out")
    parts += [f"on board: {p['what']}" for p in onboard]
    where = f" ({result['header']})" if result["header"] else ""
    summary = (f"GPIO{num} on {ctx.title}{where}: {', '.join(shown) or 'GPIO only'}; "
               f"{'; '.join(parts) if parts else 'no restrictions'}.")
    caps = ctx.data["capabilities"]
    src_ids = [caps["gpio"]["source_id"], caps["functions"]["source_id"]] + [r["source_id"] for r in rules]
    if g["adc"]:
        src_ids.append(caps["adc"]["source_id"])
    if ctx.board is not None:
        src_ids.append(ctx.board["source_id"])
    src_ids += _module_source(ctx)
    warnings, assumptions = _common_notes(ctx)
    assumptions.append(assumption("wifi", "unknown", "rules that depend on Wi-Fi show applies=null"))
    return envelope("pins.info", summary, result, warnings=warnings, assumptions=assumptions,
                    sources=_sources_for(src_ids))

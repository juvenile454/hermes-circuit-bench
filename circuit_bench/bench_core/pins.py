"""Pin rules for ESP32, ESP32-S3 and ESP32-C3.

Public action functions (result envelope, never raise):
  check(chip, assignments, *, variant=None, wifi=False, devkit=None)          -> "pins.check"
  suggest(chip, requests, *, variant, wifi, devkit, taken=(), limit=3)       -> "pins.suggest"
  info(chip, pin, *, variant, devkit)                                          -> "pins.info"
Helpers (raw data, raise BenchError): chips(), load(chip), normalize_chip(), normalize_pin().

Data: circuit_bench/data/pins/<chip>.json, generated by scripts/gen_pins.py from pinned ESP-IDF v6.1 files.
Header positions and on-board parts come from bench_core.boards. Everything is deterministic and offline.
"""
